<?php

/**
 * ============================================================================
 * ДЕКЛАРАТИВНЫЙ ФАЙЛ КОНФИГУРАЦИИ ИНТЕГРАЦИИ КЛИЕНТА (BITRIX -> VMS-NC)
 * ============================================================================
 *
 * Файл задает точные правила выгрузки, очистки, трансформации и фильтрации
 * данных из базы 1С-Битрикс в стандартизированный EAV-контракт VMS-NC / Nicole Core.
 *
 * @category IntegrationConfig
 * @package  VmsNcApi\Config
 *
 * ============================================================================
 * СПРАВОЧНИК ВСЕХ КЛЮЧЕЙ И ВАРИАНТОВ НАСТРОЙКИ:
 * ============================================================================
 *
 * ----------------------------------------------------------------------------
 * 1. ОСНОВНЫЕ МЕТАДАННЫЕ И МУЛЬТИ-КАТАЛОГИ
 * ----------------------------------------------------------------------------
 * @var string $client_code
 *      Уникальный системный код клиента (например, 'stoleshka_ru', 'akrilika_spb').
 *
 * @var string $industry
 *      Код отраслевой спецификации VMS-NC ('stone', 'wpc', 'showers', 'doors').
 *
 * @var array $locales
 *      Массив поддерживаемых языковых версий (например, ['ru'] или ['ru', 'en']).
 *
 * @var array $catalogs
 *      Массив пар инфоблоков Битрикса [ ['catalog' => ID, 'offers' => ID], ... ].
 *      Позволяет выгружать товары из нескольких независимых каталогов одновременно.
 *
 * ----------------------------------------------------------------------------
 * 2. ЦЕНЫ, ВАЛЮТЫ И КОНВЕРТЕР НАЦЕНОК
 * ----------------------------------------------------------------------------
 * @var array $pricing
 *      Привязка ID типов цен из таблицы b_catalog_group Битрикса:
 *      - retail_group_id (int): ID типа розничной цены (обычно 1).
 *      - cost_group_id   (int): ID типа закупочной себестоимости (обычно 2).
 *
 * @var array $currency_converter
 *      Правила нормализации псевдовалют и внутренних "курсов" Битрикса:
 *      - enabled (bool): Включить/выключить нормализатор в CatalogPriceRepository.
 *      - rules   (array): Таблица сопоставления внутренних кодов (STA, BLA, COR, IDS):
 *        - target_currency (string): Реальный ISO-код целевой валюты ('USD', 'EUR').
 *        - markup_percent  (float) : Процент наценки (+0.0, +20.0, +40.0, +100.0).
 *
 * @var array $currencies
 *      Список официальных ISO-валют для Nicole Core (RUB, USD, EUR):
 *      - symbol        (string) : Графический символ ('₽', '$', '€').
 *      - symbol_native (string) : Нативный символ для печатных форм КП ('руб.', '$', '€').
 *      - name          (array)  : Языковой массив названия (['ru' => 'Российский рубль']).
 *      - rate          (float)  : Точный курс валюты относительно базовой (поддерживает высокое число знаков, напр. 109.3485714).
 *      - is_default    (bool)   : Флаг базовой валюты системы (true только для одной).
 *      - use_live_rate (bool)   : true — забирать курс из Битрикса, false — брать фиксированный 'rate' из этого конфига.
 *
 * @var array $currency_map
 *      Таблица прямого сопоставления сырых кодов валют Битрикса в ISO-коды.
 *
 * @var array $price_types
 *      Список типов цен продажи для Nicole Core (slug, currency_code, is_default).
 *
 * ----------------------------------------------------------------------------
 * 3. КЛАССИФИКАЦИЯ И ДЕРЕВО КАТЕГОРИЙ
 * ----------------------------------------------------------------------------
 * @var array $product_type_rules
 *      Правила назначения типов товаров Nicole Core (type_acrylic_stone, type_kitchen_sink):
 *      - default (string): Тип по умолчанию для неразмеченных товаров.
 *      - rules   (array) : Массив правил:
 *        - type      (string): Целевой код типа товара Nicole Core.
 *        - condition (string): 'section_id' (по ID раздела) или 'regex' (по названию).
 *        - values    (array) : Массив ID разделов Битрикса (при condition = 'section_id').
 *        - field     (string): Поле Битрикса для проверки 'NAME'/'CODE' (при condition = 'regex').
 *        - pattern   (string): Регулярное выражение (при condition = 'regex').
 *
 * @var array $category_filters
 *      Правила фильтрации дерева разделов Битрикса:
 *      - mode                 (string): FilterMode::WHITELIST или FilterMode::BLACKLIST.
 *      - include_section_ids  (array) : Массив разрешенных ID разделов.
 *      - exclude_section_ids  (array) : Массив запрещенных ID разделов.
 *      - external_code_prefix (string): Префикс внешнего кода категории ('cat_').
 *
 * ----------------------------------------------------------------------------
 * 4. ОПИСАНИЯ И МНОГОУРОВНЕВАЯ ФИЛЬТРАЦИЯ (ОЧИСТКА МУСОРА)
 * ----------------------------------------------------------------------------
 * @var array $description_map
 *      Карта источников текстовых описаний:
 *      - short_description : ['sources' => ['PREVIEW_TEXT']] (короткий анонс).
 *      - description       : ['sources' => ['DETAIL_TEXT']] (полное описание).
 *
 * @var array $product_filters
 *      Правила исключения базовых товаров с поддержкой ConditionEvaluator:
 *      - rules (array): Массив условий с точечной нотацией:
 *        - when (array): ['bitrix.property.SNYAT' => 'Y'], ['bitrix.field.NAME' => '/столешниц|кронштейн/ui'].
 *
 * @var array $offer_filters
 *      Черный список для торговых предложений SKU (отсечение 1/2, 1/4, обрезков и смет):
 *      - mode  (string): FilterMode::BLACKLIST или FilterMode::WHITELIST.
 *      - rules (array) : Массив правил с поддержкой 'when' или 'pattern'.
 *
 * ----------------------------------------------------------------------------
 * 5. РАНЖИРОВАНИЕ И ПРИОРИТЕТЫ ВАРИАЦИЙ (CPQ LOGIC)
 * ----------------------------------------------------------------------------
 * @var array $variant_priority_rules
 *      Правила выбора единственного первичного (дефолтного) слэба/листа для калькулятора.
 *      Ключом выступает код типа товара ('type_acrylic_stone', 'type_quartz_stone').
 *      - mode (string):
 *        - 'single_primary' : Оставить ровно 1 наилучшую вариацию, удалив остальные.
 *        - 'set_default'     : Сохранить все варианты, но сделать лучший дефолтным (is_default=true).
 *      - rules (array): Упорядоченный каскад критериев оценки:
 *        - attribute (string): Код EAV-характеристики ('height', 'length', 'width').
 *        - type      (string):
 *          - 'match_order' : Сравнение со списком предпочтений. Требует 'values' => [...].
 *          - 'sort'        : Числовая сортировка. Требует 'order' => 'desc'/'max' или 'asc'/'min'.
 *        - values    (array) : Список приоритетных значений по порядку (например [20, 15, 30, 12]).
 *        - order     (string): 'desc' (чем больше, тем лучше) или 'asc' (чем меньше, тем лучше).
 *
 * ----------------------------------------------------------------------------
 * 6. ЕДИНООБРАЗНАЯ КАРТА EAV-АТРИБУТОВ (property_map)
 * ----------------------------------------------------------------------------
 * @var array $property_map
 *      Ассоциативный массив маппинга EAV-атрибутов Nicole Core (ключ — системный код атрибута):
 *      - source       (string): Код основного свойства Битрикс ('BRAND_REF').
 *      - sources      (array) : Каскадный список кодов свойств Битрикс по приоритету.
 *                               Движок берет первое непустое значение (['COLOR', 'CVET_BLANCO']).
 *      - fallback     (string): Резервное поле элемента Битрикс, если свойства пустые ('CODE', 'NAME').
 *      - default      (mixed) : Гибкий дефолт через ConditionEvaluator (скаляр или правила 'rules'):
 *        - rules -> [ ['when' => ['product.type' => 'type_quartz_stone'], 'value' => 20] ]
 *        - fallback -> Резервное значение, если правила не совпали.
 *      - type         (string): Тип данных Nicole Core ('enum', 'hl', 'numeric', 'string', 'boolean').
 *      - prefix       (string): Префикс внешнего кода опции ('opt_brand_').
 *      - name         (array) : Мультиязычное название характеристики (['ru' => 'Длина (мм)']).
 *      - scope        (string): Область видимости атрибута:
 *                               - 'product' : Только на уровне базового товара.
 *                               - 'variant' : Только на уровне торгового предложения (SKU).
 *                               - 'both'    : И на уровне товара, и на уровне вариаций (с авто-наследованием от родителя).
 *      - transformers (array) : Цепочка классов-трансформеров значений:
 *        - RegexExtractor : Извлечение чисел/текста по регулярке (pattern, group).
 *        - CastToInteger  : Приведение значения к целым числам.
 *        - EnumToBoolean  : Преобразование текстовых статусов ('yes_bend') в boolean (true/false).
 *      - settings     (array) : Настройки публичности и UI-фильтров в каналах продаж:
 *        - channels -> widget/catalog:
 *          - is_public          (bool)  : Публиковать ли атрибут в API.
 *          - is_settings_public (bool)  : Публиковать ли мета-настройки.
 *          - is_filterable      (bool)  : Выводить ли атрибут в панели фильтров UI.
 *          - is_collapsed       (bool)  : Свернуть ли фильтр по умолчанию.
 *          - filter_type        (string): Тип UI-компонента фильтра ('color', 'range', 'checkbox', 'radio').
 *
 * ----------------------------------------------------------------------------
 * 7. ДЕКЛАРАТИВНЫЕ ПРАВИЛА АУДИТОВ (audits)
 * ----------------------------------------------------------------------------
 * @var array $audits
 *      Настройки универсальных проверок полноты данных для отладки (?debug=true&method=meta/dims):
 *      - dims -> required_eav : ['length', 'width', 'height']
 *      - meta -> required_eav : ['brand', 'collection']
 */